def team_zh(name: str) -> str:
    """将英文队名转换为中文名，找不到则返回原文"""
    if not name:
        return name
    key = name.strip().lower()
    # 1. 精确匹配
    if key in TEAM_ZH:
        return TEAM_ZH[key]
    # 2. 去除常见后缀再试
    for suffix in (" w", " fc", " sc", " bc", " sk", " bk", " cf", " cd", " ac"):
        if key.endswith(suffix):
            stripped = key[: -len(suffix)].strip()
            if stripped in TEAM_ZH:
                return TEAM_ZH[stripped]
    # 3. 包含匹配（字典key是名称子串，要求key≥7字符且按词边界匹配，避免误匹配）
    import re as _re
    for k, v in TEAM_ZH.items():
        if len(k) < 7:
            continue
        # key必须作为独立词组出现（前后是空格/字符串边界），防止 mexico 匹配 new mexico
        if _re.search(r'(?<![a-z])' + _re.escape(k) + r'(?![a-z])', key):
            return v
    return name  # 无匹配，保留英文
