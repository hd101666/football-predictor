# ─── PERF-001（2026-09-16 owner裁决）：模糊回退的性能与可观测性改造 ──────────
# 实证假死链：predict_football._fit_dc_rho 采样8000场逐场 _poisson_predict →
# 每场 team_en×2 → 未命中时全表3062词条 SequenceMatcher 扫描，无缓存无早退，
# 最坏≈4900万次构造（reports/backlog_20260916_26127.md PERF-001）。
# 改造四条：①lru_cache（TEAM_CN_TO_EN 仅 import 期构建，运行时无改写，缓存安全）
# ②长度上界早退剪枝（ratio≤2·min(la,lb)/(la+lb)，不超过当前最优/阈值的候选跳过，
#   数学上界恒真，不改变选出结果）③单调用耗时上限+全程耗时/撞车率日志
# ④模糊回退黑名单（已知跨运动撞车输入，禁模糊直接原样返回）。
# 行为兼容承诺：除黑名单输入外，返回值与旧版逐字节一致（同一阈值0.7、同一
# "严格大于才换最优"的平局取先者规则）。
from functools import lru_cache as _lru_cache
import logging as _logging
import time as _time

_TEAM_EN_FUZZY_BLACKLIST = {
    # 0906实证跨运动撞车输入：足球"多伦多( FC)"曾被模糊回退撞去NBA猛龙
    "多伦多", "多伦多FC",
}
_FUZZY_THRESHOLD = 0.7          # 与旧版一致，勿单独调（属模型输入口径）
_FUZZY_MAX_SECONDS = 1.5        # 单次模糊扫描耗时上限，超时按当前最优早退+WARNING
_FUZZY_WARN_LIMIT = 20          # 每进程撞车WARNING前N条全文，其后只计数（防刷屏）

_TEAM_EN_STATS = {
    "calls": 0, "exact_hits": 0, "blacklisted": 0,
    "fuzzy_scans": 0,           # 进入模糊扫描的调用数（缓存未命中的不同名）
    "fuzzy_used": 0,            # 模糊回退被采用（撞车风险观察对象）
    "pruned": 0,                # 被长度上界剪掉的候选数
    "time_capped": 0, "slow_calls": 0,
}
_TEAM_EN_WARNED = 0
_log = _logging.getLogger("team_mapping")


def _fuzzy_lookup(name: str):
    """全表模糊扫描（带长度上界剪枝+耗时上限）。返回 (en结果或None, best_ratio)。
    本函数被 lru_cache 包裹：只有缓存未命中（新队名）才会真的执行扫描。"""
    from difflib import SequenceMatcher
    _TEAM_EN_STATS["fuzzy_scans"] += 1
    best, best_ratio = None, 0.0
    la = len(name)
    t0 = _time.perf_counter()
    scanned = 0
    for cn in TEAM_CN_TO_EN:
        lb = len(cn)
        # 长度上界剪枝：ratio 上界 = 2·min/(la+lb)，超不过 max(当前最优,阈值) 的候选
        # 永远不可能被采用，跳过（上界恒真，不影响结果）
        if 2.0 * min(la, lb) <= max(best_ratio, _FUZZY_THRESHOLD) * (la + lb):
            _TEAM_EN_STATS["pruned"] += 1
            continue
        scanned += 1
        ratio = SequenceMatcher(None, name, cn).ratio()
        if ratio > best_ratio:
            best_ratio = ratio
            best = cn
        if scanned % 64 == 0 and _time.perf_counter() - t0 > _FUZZY_MAX_SECONDS:
            _TEAM_EN_STATS["time_capped"] += 1
            _log.warning("team_en模糊扫描超上限(%.1fs)早退: 输入=%r 已扫%d/%d 当前最优=%r(%.3f)",
                         _time.perf_counter() - t0, name, scanned, len(TEAM_CN_TO_EN),
                         best, best_ratio)
            break
    dt = _time.perf_counter() - t0
    if dt > 0.5:
        _TEAM_EN_STATS["slow_calls"] += 1
        _log.warning("team_en模糊扫描慢调用: %.2fs 输入=%r 扫描%d条", dt, name, scanned)
    if best_ratio > _FUZZY_THRESHOLD and best is not None:
        return TEAM_CN_TO_EN[best], best_ratio
    return None, best_ratio


# 缓存的是"扫描结果"本身：同名输入只扫一次全表（8000场采样里不同队名仅数百，
# 重复调用全部命中缓存——PERF-001验收点②）
_fuzzy_cached = _lru_cache(maxsize=8192)(_fuzzy_lookup)


def team_en(name_cn):
    """中文队名转英文（PERF-001版：精确→黑名单→缓存模糊，全程留痕）"""
    _TEAM_EN_STATS["calls"] += 1
    key = name_cn.strip()
    result = TEAM_CN_TO_EN.get(key)
    if result:
        _TEAM_EN_STATS["exact_hits"] += 1
        return result
    if key in _TEAM_EN_FUZZY_BLACKLIST:
        _TEAM_EN_STATS["blacklisted"] += 1
        _log.warning("team_en命中模糊回退黑名单，原样返回: %r", key)
        return name_cn
    global _TEAM_EN_WARNED
    en, ratio = _fuzzy_cached(key)
    if en is None:
        return name_cn
    _TEAM_EN_STATS["fuzzy_used"] += 1
    if _TEAM_EN_WARNED < _FUZZY_WARN_LIMIT:
        _TEAM_EN_WARNED += 1
        _log.warning("team_en模糊回退命中(撞车观察): %r → %r (ratio=%.3f)", key, en, ratio)
    return en


def team_en_stats() -> dict:
    """模糊回退可观测性读数（撞车率=fuzzy_used/calls）。只读快照，供跑批尾部打印。"""
    s = dict(_TEAM_EN_STATS)
    s["cache_info"] = str(_fuzzy_cached.cache_info())
    s["collision_rate"] = (s["fuzzy_used"] / s["calls"]) if s["calls"] else 0.0
    return s
